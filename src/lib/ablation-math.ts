import { WeightDistribution, OptunaTrial, HereticSettings, AbliterationParameters, ModelPreset } from '../types/heretic';

/**
 * Computes layer ablation weights according to Heretic's trapezoidal/triangular
 * weight distribution kernel across layers:
 * 
 * distance = |layer_index - max_weight_position|
 * if distance > min_weight_distance: weight = 0
 * else: weight = max_weight + (distance / min_weight_distance) * (min_weight - max_weight)
 */
export function calculateLayerWeights(
  totalLayers: number,
  dist: WeightDistribution
): { layer: number; weight: number }[] {
  const result: { layer: number; weight: number }[] = [];

  for (let layer = 0; layer < totalLayers; layer++) {
    const distance = Math.abs(layer - dist.max_weight_position);

    if (distance > dist.min_weight_distance) {
      result.push({ layer, weight: 0 });
    } else {
      const weight = dist.max_weight + 
        (distance / dist.min_weight_distance) * (dist.min_weight - dist.max_weight);
      result.push({ layer, weight: Math.max(0, Number(weight.toFixed(4))) });
    }
  }

  return result;
}

/**
 * Computes the Pareto frontier for multi-objective optimization:
 * Minimizing both Refusal Rate (X) and KL Divergence (Y).
 * A point is non-dominated if no other point has both lower or equal in both with at least one strictly lower.
 */
export function markParetoOptimal(trials: OptunaTrial[]): OptunaTrial[] {
  return trials.map((candidate, _, all) => {
    // Check if any other trial dominates candidate
    const isDominated = all.some(other => {
      if (other.trialIndex === candidate.trialIndex) return false;
      const otherBetterOrEqualRefusal = other.refusalRate <= candidate.refusalRate;
      const otherBetterOrEqualKL = other.klDivergence <= candidate.klDivergence;
      const otherStrictlyBetterOne = 
        other.refusalRate < candidate.refusalRate || other.klDivergence < candidate.klDivergence;
      
      return otherBetterOrEqualRefusal && otherBetterOrEqualKL && otherStrictlyBetterOne;
    });

    return {
      ...candidate,
      isParetoOptimal: !isDominated
    };
  });
}

/**
 * Generates valid Heretic TOML config formatted as used by `heretic --config config.toml`
 */
export function generateTomlConfig(
  settings: HereticSettings,
  abliterationParams: AbliterationParameters
): string {
  const { attention, mlp } = abliterationParams.weight_distributions;
  
  return `# Heretic Configuration File
# Generated by Heretic Decensoring Studio
# For details see: https://github.com/p-e-w/heretic

model = "${settings.model}"
quantization = "${settings.quantization}"
dtypes = [${settings.dtypes.map(d => `"${d}"`).join(', ')}]
device_map = "${settings.deviceMap}"
offload_outputs_to_cpu = ${settings.offloadOutputsToCpu}
batch_size = ${settings.batchSize}
max_response_length = ${settings.maxResponseLength}
export_strategy = "${settings.exportStrategy}"

n_trials = ${settings.nTrials}
n_startup_trials = ${settings.nStartupTrials}
study_checkpoint_dir = "checkpoints"

scorers = [
  { plugin = "heretic.scorers.keyword_rate.KeywordRate", optimization = "minimize" },
  { plugin = "heretic.scorers.kl_divergence.KLDivergence", optimization = "minimize" },
]

modifiers = [
  { plugin = "${settings.modifierPlugin === 'ara' ? 'heretic.modifiers.ara.ARA' : 'heretic.modifiers.abliteration.Abliteration'}" },
]

[modifier.${settings.modifierPlugin === 'ara' ? 'ARA' : 'Abliteration'}.good_prompts]
dataset = "${settings.goodPromptsDataset}"
split = "${settings.goodPromptsSplit}"
column = "text"

[modifier.${settings.modifierPlugin === 'ara' ? 'ARA' : 'Abliteration'}.bad_prompts]
dataset = "${settings.badPromptsDataset}"
split = "${settings.badPromptsSplit}"
column = "text"

[reproduce.parameters]
direction_index = ${abliterationParams.direction_index === null ? '"per layer"' : abliterationParams.direction_index.toFixed(2)}
"attention.max_weight" = ${attention.max_weight.toFixed(3)}
"attention.max_weight_position" = ${attention.max_weight_position.toFixed(1)}
"attention.min_weight" = ${attention.min_weight.toFixed(3)}
"attention.min_weight_distance" = ${attention.min_weight_distance.toFixed(1)}
"mlp.max_weight" = ${mlp.max_weight.toFixed(3)}
"mlp.max_weight_position" = ${mlp.max_weight_position.toFixed(1)}
"mlp.min_weight" = ${mlp.min_weight.toFixed(3)}
"mlp.min_weight_distance" = ${mlp.min_weight_distance.toFixed(1)}
`;
}

